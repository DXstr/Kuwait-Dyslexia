# Gradio-SDK entry point: our FastAPI app on port 7860, Gradio notice mounted at /ui
APP_PY = '''"""Hugging Face Space entry point (generated by ai/scripts/deploy_hf_space.py; do not edit here)."""

import os
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE / "ai"))
os.environ.setdefault("BASIRA_CONTRACTS_DIR", str(HERE / "contracts"))

import gradio as gr  # noqa: E402
import uvicorn  # noqa: E402
from fastapi.responses import RedirectResponse  # noqa: E402

from service.app import build  # noqa: E402

api = build()


@api.get("/", include_in_schema=False)
def root():
    return RedirectResponse("/docs")


with gr.Blocks(title="Basira scorer") as notice:
    gr.Markdown("# Basira scorer\\nAPI only. `GET /health` for status, `/docs` for the endpoints. "
                "Scoring requires a Basira (Supabase) access token.")

app = gr.mount_gradio_app(api, notice, path="/ui")

if __name__ == "__main__":
    uvicorn.run(app, host="0.0.0.0", port=int(os.environ.get("PORT", "7860")))
'''

# ZeroGPU supports torch 2.8.0+ only; versions otherwise follow ai/pyproject.toml ([model] + [service] extras)
