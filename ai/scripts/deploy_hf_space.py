"""Deploy the scorer to a Hugging Face Space (task A13).

Free accounts can no longer create Docker Spaces (they need PRO); the free path is a **Gradio-SDK Space on ZeroGPU**
(account older than 30 days, verified email; https://huggingface.co/docs/hub/spaces-zerogpu). This script stages a
Gradio-SDK Space whose `app.py` serves our unchanged FastAPI app (every REST endpoint of contracts/scorer.openapi.yaml)
and mounts a one-page Gradio notice at /ui, because the Gradio SDK runs `python app.py`.

The acoustic models run on the Space's CPU inside the REST handlers (ZeroGPU only lends a GPU to `@spaces.GPU`
functions; using it from REST calls is not documented, so we do not depend on it). `--sdk docker` keeps the original
Docker image path for a PRO account or another host.

Usage (from the repo root):
    HF_TOKEN=hf_... python ai/scripts/deploy_hf_space.py --space <user>/basira-scorer \
        --jwks-url https://<project>.supabase.co/auth/v1/.well-known/jwks.json \
        --allowed-origins https://basira.pages.dev,http://localhost:5173
    python ai/scripts/deploy_hf_space.py --space x/y --dry-run      # stage into ./space-preview only

The Space is public (the web app calls it without a Hugging Face token); every scoring endpoint still requires a
Supabase access token, so public only means "reachable", as for any API.
"""

