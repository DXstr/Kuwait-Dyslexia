def stage(dest: Path, sdk: str = "gradio") -> None:
    for rel in INCLUDE:
        src = ROOT / rel
        if src.is_dir():
            shutil.copytree(src, dest / rel, ignore=SKIP)
        else:
            (dest / rel).parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src, dest / rel)
    if sdk == "docker":
        shutil.copy2(ROOT / "ai" / "Dockerfile", dest / "Dockerfile")
    else:
        (dest / "app.py").write_text(APP_PY, encoding="utf-8", newline="\n")
        (dest / "requirements.txt").write_text(REQUIREMENTS, encoding="utf-8", newline="\n")
    (dest / "README.md").write_text(CARD[sdk] + BODY, encoding="utf-8", newline="\n")


def space_url(space: str) -> str:
    user, name = space.split("/", 1)
    return f"https://{user.lower()}-{name.lower().replace('_', '-').replace('.', '-')}.hf.space"


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--space", required=True, help="<hf-user>/<space-name>")
    p.add_argument("--sdk", choices=["gradio", "docker"], default="gradio",
                   help="gradio = free ZeroGPU route (default); docker needs HF PRO")
    p.add_argument("--jwks-url", default=os.environ.get("SUPABASE_JWKS_URL"), help="Supabase JWKS URL (public)")
    p.add_argument("--allowed-origins", default=os.environ.get("ALLOWED_ORIGINS"), help="comma-separated origins")
    p.add_argument("--dry-run", action="store_true", help="stage into ./space-preview and stop")
    a = p.parse_args(argv)

    if a.dry_run:
        out = Path("space-preview")
        shutil.rmtree(out, ignore_errors=True)
        stage(out, a.sdk)
        print(f"staged ({a.sdk}) into {out.resolve()}")
        return 0

    token = os.environ.get("HF_TOKEN")
    if not token:
        print("set HF_TOKEN (a Hugging Face token with write access)", file=sys.stderr)
        return 2
    if not a.jwks_url:
        print("set --jwks-url (or SUPABASE_JWKS_URL): the scorer refuses to start without a token verifier",
              file=sys.stderr)
        return 2
    from huggingface_hub import HfApi

    api = HfApi(token=token)
    api.create_repo(a.space, repo_type="space", space_sdk=a.sdk, private=False, exist_ok=True)
    # configuration is not secret: the JWKS URL and origins are public values, so they are Space variables
    for key, value in (("SUPABASE_JWKS_URL", a.jwks_url), ("ALLOWED_ORIGINS", a.allowed_origins)):
        if value:
            api.add_space_variable(a.space, key, value)
    with tempfile.TemporaryDirectory() as tmp:
        stage(Path(tmp), a.sdk)
        info = api.upload_folder(
            repo_id=a.space, repo_type="space", folder_path=tmp, delete_patterns="*",
            commit_message=f"deploy from {os.environ.get('GITHUB_SHA', 'local')[:12]}",
        )
    if a.sdk == "gradio":
        try:
            api.request_space_hardware(a.space, "zero-a10g")
        except Exception as e:  # noqa: BLE001 - report and continue: the Space still runs on free CPU
            print(f"note: could not select ZeroGPU hardware ({e}); select it in the Space settings")
    print(f"pushed {info.oid[:12]}; build log: https://huggingface.co/spaces/{a.space}")
    print(f"API URL: {space_url(a.space)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
